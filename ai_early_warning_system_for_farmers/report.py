"""
report.py — Downloadable Scan Report Generator
AI Plant Doctor — Smart Plant Identification, Disease Detection & Farming Early Warning System
"""

from datetime import datetime
from typing import Any, Dict, Optional


def generate_text_report(
    scan_result: Dict[str, Any],
    plant_info: Optional[Dict[str, Any]] = None,
    disease_info: Optional[Dict[str, Any]] = None,
    weather_summary: Optional[str] = None,
    lang: str = "en"
) -> str:
    """
    Generate a structured plain-text scan report for download.
    Only includes actual data — no fabricated values.
    """
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    sep = "=" * 68
    thin = "-" * 68

    lines = [
        sep,
        "  AI PLANT DOCTOR -- AGRICULTURAL SCAN REPORT",
        "  Smart Plant Identification, Disease Detection & Early Warning",
        sep,
        f"  Report Generated : {now}",
        f"  Scan Reference   : {scan_result.get('scan_uuid', 'N/A')}",
        f"  Scan Timestamp   : {scan_result.get('timestamp', 'N/A')}",
        f"  Scan Type        : {scan_result.get('scan_type', 'N/A')}",
        thin,
    ]

    plant_name = scan_result.get("selected_plant", "Unknown")
    predicted = scan_result.get("predicted_class", "Unknown")
    confidence = scan_result.get("confidence")
    conf_str = f"{confidence * 100:.1f}%" if confidence is not None else "N/A"
    uncertain = scan_result.get("is_uncertain", False)

    lines += [
        "  SCAN RESULTS",
        thin,
        f"  Plant Identified : {plant_name}",
        f"  Predicted Result : {predicted}",
        f"  Confidence Score : {conf_str}",
        f"  Uncertain Result : {'YES -- Please consult an agricultural expert' if uncertain else 'NO'}",
        thin,
    ]

    if plant_info:
        sci = plant_info.get("scientific_name", "N/A")
        category = plant_info.get("category", "N/A")
        family = plant_info.get("family", "N/A")
        gc = plant_info.get("growing_conditions", {})
        lines += [
            "  PLANT INFORMATION (FROM KNOWLEDGE BASE)",
            thin,
            f"  Scientific Name  : {sci}",
            f"  Family           : {family}",
            f"  Category         : {category}",
            f"  Sunlight         : {gc.get('sunlight', 'N/A')}",
            f"  Watering         : {gc.get('watering', 'N/A')}",
            f"  Soil             : {gc.get('soil', 'N/A')}",
            f"  Temperature      : {gc.get('temperature_c', 'N/A')}",
            thin,
        ]

    if disease_info:
        dname = disease_info.get("name", {}).get("en", "N/A")
        symptoms = disease_info.get("symptoms", {}).get("en", [])
        prevention = disease_info.get("prevention", {}).get("en", [])
        treatment = disease_info.get("treatment", {}).get("en", [])
        lines += [
            "  DISEASE / CONDITION INFORMATION",
            thin,
            f"  Condition        : {dname}",
        ]
        if symptoms:
            lines.append("  Symptoms:")
            for s in symptoms[:5]:
                lines.append(f"    * {s}")
        if prevention:
            lines.append("  Prevention Measures:")
            for p in prevention[:4]:
                lines.append(f"    * {p}")
        if treatment:
            lines.append("  Treatment Guidance:")
            for tr in treatment[:4]:
                lines.append(f"    * {tr}")
        lines.append(thin)

    if weather_summary:
        lines += [
            "  WEATHER ADVISORY AT TIME OF SCAN",
            thin,
            f"  {weather_summary}",
            thin,
        ]

    lines += [
        "  IMPORTANT DISCLAIMER",
        thin,
        "  1. This report is generated by an AI system for decision-support purposes only.",
        "  2. Predictions may be less accurate on real field photographs.",
        "  3. This is NOT a replacement for certified agricultural extension officers or KVK.",
        "  4. Never apply pesticides without consulting official product labels and your",
        "     local Block Agricultural Officer.",
        "  5. Always verify government scheme details at official portals before applying.",
        sep,
        "  AI Plant Doctor v2.0 | TNAU Knowledge Base | Open-Meteo Weather",
        sep,
    ]

    return "\n".join(lines)
